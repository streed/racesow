"""Racesow dev textures, skybox and shaders, generated: no binary blobs in git.

The look borrows the site's palette (web/public/assets/css: --orange #ff6a1a,
--cyan #22d3ee, --green #a9f26a on navy) and the conventions of a dev
texture set. Every surface carries a measuring grid, because a racer reads
distances off the floor:

    floor       light grey, 64-unit cells, 16-unit sub-grid, unit labels
    wall        dark slate, the same grid; clearly darker than any floor
    start       navy pad, green chevrons pointing down the course, "START"
    finish      black / white checker with an orange "FINISH" band
    checkpoint  cyan line strip with "CP" markers
    edge        orange / black hazard stripes on every gap lip
    trim        orange racing stripe on the start and finish lines
    pylon       slalom and split fins: navy with cyan bands, "go round me"
    kick        wall-jump walls: yellow chevrons pointing up on navy, "kick off me"
    ice         slick floor: pale ice blue, the same grid, frost glints, "ICE";
                its shader carries surfaceparm slick (no ground friction)

Textures are 256 px and mapfile.TEX_SCALE is 1, so 1 px = 1 game unit and
the grid is true to scale.

Everything lives under a versioned name (mapgen_v1) and ships INSIDE each
generated .pk3, so a map is self-contained: a client that downloads it gets
the look with it. Two generated maps carry byte-identical copies, and the
engine resolves the duplicate shader names to the same thing. Once a map
using a version is published, never edit that version in place: bump it.
Otherwise two installed maps would disagree about what mapgen_v1/floor means
and load order would pick one. (v1 is still unpublished.)
"""

import struct

VERSION = "mapgen_v1"
SIZE = 256

ORANGE = (255, 106, 26)
ORANGE_DIM = (193, 78, 16)
CYAN = (34, 211, 238)
GREEN = (169, 242, 106)
NAVY = (21, 24, 36)
NAVY_2 = (38, 43, 61)
WHITE = (232, 235, 245)
YELLOW = (250, 204, 21)
BLACK = (18, 19, 24)

SHADER = f"""// generated by tools/mapgen/assets.py
textures/{VERSION}/sky
{{
	qer_editorimage env/{VERSION}/sky_up.tga
	surfaceparm sky
	surfaceparm noimpact
	surfaceparm nolightmap
	surfaceparm nomarks
	q3map_sun 1 0.97 0.9 25 35 55
	q3map_skylight 30 3
	skyparms env/{VERSION}/sky - -
}}

textures/{VERSION}/trigger
{{
	qer_trans 0.4
	surfaceparm nodraw
	surfaceparm nolightmap
	surfaceparm nomarks
	surfaceparm trans
}}

// An origin brush: the ONLY thing that gives a brush entity its own coordinate
// frame. q3map2 takes the centre of a brush wearing this shader as the
// entity's origin, subtracts it from the entity's other brushes and drops the
// brush itself, so the compiled inline model is expressed around that point.
// An "origin" KEY does not do this — measured, not assumed: a key alone leaves
// the submodel at its world position, which puts a dealt tile wherever it
// happened to be compiled instead of where it is placed. Setting both is worse
// than either, because q3map2 ADDS the key to the brush-derived origin.
// Used by tiles.py; a written course has no brush entity that needs a frame.
textures/{VERSION}/origin
{{
	qer_trans 0.3
	surfaceparm origin
	surfaceparm nodraw
	surfaceparm nolightmap
	surfaceparm nomarks
	surfaceparm trans
}}
"""

# Ice has its own shader file rather than an entry in SHADER above. Packs
# already in the map store carry scripts/mapgen_v1.shader WITHOUT it, and when
# two packs hold the same path the engine reads only one of them, so an ice
# entry added there could be shadowed by an older pack. A file name no
# published pack has cannot be. It ships only in packs whose course uses ice
# (files(ice=True)), so a course without ice packs the same bytes as before.
#
# surfaceparm slick is a COMPILE-time property: q3map2 writes SURF_SLICK into
# the bsp's shaderref flags, and that is what the engine's movement code and
# the site's slick scan (web/bsp.js parseSlick) read. build.check_bsp confirms
# it survived compilation.
ICE_SHADER_PATH = f"scripts/{VERSION}_ice.shader"
ICE_SHADER = f"""// generated by tools/mapgen/assets.py
textures/{VERSION}/ice
{{
	qer_editorimage textures/{VERSION}/ice.tga
	surfaceparm slick
	{{
		map $lightmap
		rgbGen identity
	}}
	{{
		map textures/{VERSION}/ice.tga
		blendFunc filter
	}}
}}
"""

